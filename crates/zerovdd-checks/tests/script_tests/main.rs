use std::fs;
use std::path::{Path, PathBuf};
use std::process::{Command, Output};

use tempfile::TempDir;
use zerovdd_checks::{find_bash_executable, repo_root};

fn run_git(dir: &Path, args: &[&str]) -> Output {
    let output = Command::new("git")
        .args(args)
        .current_dir(dir)
        .output()
        .expect("failed to execute git");
    assert!(
        output.status.success(),
        "git {:?} failed: stdout={} stderr={}",
        args,
        String::from_utf8_lossy(&output.stdout),
        String::from_utf8_lossy(&output.stderr)
    );
    output
}

fn run_bash_script(cwd: &Path, script: &Path, args: &[&str]) -> Output {
    let bash = find_bash_executable();
    let script_str = script.to_string_lossy().replace('\\', "/");
    Command::new(bash)
        .arg(script_str)
        .args(args)
        .current_dir(cwd)
        .output()
        .expect("failed to execute bash script")
}

fn init_temp_git_repo() -> TempDir {
    let dir = TempDir::new().expect("create temp dir");
    run_git(dir.path(), &["init", "-b", "main"]);
    run_git(dir.path(), &["config", "user.name", "Test User"]);
    run_git(
        dir.path(),
        &["config", "user.email", "test@example.invalid"],
    );
    dir
}

fn hook_path(name: &str) -> PathBuf {
    repo_root().join(".githooks").join(name)
}

fn script_path(name: &str) -> PathBuf {
    repo_root().join("scripts").join(name)
}

#[test]
fn commit_msg_hook_rejects_ai_attribution_robot_emoji_and_emdash_without_false_positives() {
    let tmp = TempDir::new().expect("create temp dir");
    let hook = hook_path("commit-msg");

    for (name, content) in [
        (
            "coauthor_claude.txt",
            "feat(core): add parser\n\nCo-Authored-By: Claude <noreply@anthropic.com>\n"
                .to_string(),
        ),
        (
            "coauthor_cursor.txt",
            "feat(core): add parser\n\nCo-Authored-By: Cursor <bot@cursor.sh>\n".to_string(),
        ),
        (
            "generated_cursor_ai.txt",
            "feat(core): add parser\n\nGenerated with Cursor AI\n".to_string(),
        ),
        (
            "generated_ai.txt",
            "feat(core): add parser\n\nGenerated by AI\n".to_string(),
        ),
        (
            "generated_gemini.txt",
            "feat(core): add parser\n\nGenerated with Gemini\n".to_string(),
        ),
        (
            "generated_gpt.txt",
            "feat(core): add parser\n\nGenerated with GPT\n".to_string(),
        ),
        (
            "machine_written.txt",
            "feat(core): add parser\n\nMachine-written commit.\n".to_string(),
        ),
        (
            "posted_by_agent.txt",
            "feat(core): add parser\n\nPosted by an AI agent.\n".to_string(),
        ),
        (
            "authored_by_claude.txt",
            "feat(core): add parser\n\nThis commit was authored by Claude.\n".to_string(),
        ),
        ("robot.txt", format!("chore: bootstrap {}\n", '\u{1F916}')),
        (
            "emdash.txt",
            format!("feat(core): fast {} clean\n", '\u{2014}'),
        ),
    ] {
        let msg_path = tmp.path().join(name);
        fs::write(&msg_path, content).unwrap();
        let out = run_bash_script(tmp.path(), &hook, &[msg_path.to_str().unwrap()]);
        assert!(
            !out.status.success(),
            "commit-msg hook must reject fixture {name}"
        );
    }

    for (name, content) in [
        (
            "good_clean.txt",
            "feat(core): add versioned protocol framing\n",
        ),
        (
            "good_detailed.txt",
            "fix(edid): validate checksum generated by detailed timing\n",
        ),
        (
            "good_cursor.txt",
            "fix(driver): drop handle generated by cursor setup\n",
        ),
    ] {
        let msg_path = tmp.path().join(name);
        fs::write(&msg_path, content).unwrap();
        let out = run_bash_script(tmp.path(), &hook, &[msg_path.to_str().unwrap()]);
        assert!(
            out.status.success(),
            "commit-msg hook must accept {name}, stderr={}",
            String::from_utf8_lossy(&out.stderr)
        );
    }
}

#[test]
fn pre_commit_hook_blocks_staged_emdash_and_honors_escape_hatch_and_exemptions() {
    let repo = init_temp_git_repo();
    let hook = hook_path("pre-commit");

    let rs_file = repo.path().join("sample.rs");
    fs::write(
        &rs_file,
        format!("/// Bad {} comment.\npub fn demo() {{}}\n", '\u{2014}'),
    )
    .unwrap();
    run_git(repo.path(), &["add", "sample.rs"]);

    let out_bad = run_bash_script(repo.path(), &hook, &[]);
    assert!(
        !out_bad.status.success(),
        "pre-commit hook must reject staged .rs containing em dash"
    );

    fs::write(
        &rs_file,
        format!(
            "/// Allowed {} comment. ok-emdash\npub fn demo() {{}}\n",
            '\u{2014}'
        ),
    )
    .unwrap();
    run_git(repo.path(), &["add", "sample.rs"]);

    let out_escaped = run_bash_script(repo.path(), &hook, &[]);
    assert!(
        out_escaped.status.success(),
        "pre-commit hook must accept line tagged ok-emdash, stderr={}",
        String::from_utf8_lossy(&out_escaped.stderr)
    );

    fs::create_dir_all(repo.path().join("plans")).unwrap();
    fs::write(
        repo.path().join("plans/notes.md"),
        format!("Plan {} note\n", '\u{2014}'),
    )
    .unwrap();
    fs::write(
        repo.path().join("CHANGELOG.md"),
        format!("- Item {} note\n", '\u{2014}'),
    )
    .unwrap();
    run_git(repo.path(), &["add", "plans/notes.md", "CHANGELOG.md"]);

    let out_exempt = run_bash_script(repo.path(), &hook, &[]);
    assert!(
        out_exempt.status.success(),
        "pre-commit hook must ignore plans/ and CHANGELOG.md, stderr={}",
        String::from_utf8_lossy(&out_exempt.stderr)
    );
}

#[test]
fn check_emdash_diff_handles_unborn_head_and_branch_diffs() {
    let repo = init_temp_git_repo();
    let script = script_path("check-emdash-diff.sh");

    fs::write(
        repo.path().join("README.md"),
        format!("Bad {}\n", '\u{2014}'),
    )
    .unwrap();
    run_git(repo.path(), &["add", "README.md"]);
    let out_unborn = run_bash_script(repo.path(), &script, &[]);
    assert!(
        !out_unborn.status.success(),
        "check-emdash-diff.sh must detect staged em dash on unborn HEAD"
    );

    fs::write(repo.path().join("README.md"), "Clean baseline\n").unwrap();
    run_git(repo.path(), &["add", "README.md"]);
    run_git(repo.path(), &["commit", "-m", "chore: initial"]);

    let out_clean = run_bash_script(repo.path(), &script, &[]);
    assert!(
        out_clean.status.success(),
        "check-emdash-diff.sh must pass on clean repo, stderr={}",
        String::from_utf8_lossy(&out_clean.stderr)
    );

    run_git(repo.path(), &["checkout", "-b", "feat/test"]);
    fs::write(
        repo.path().join("lib.rs"),
        format!("pub const MSG: &str = \"hello {} world\";\n", '\u{2014}'),
    )
    .unwrap();
    run_git(repo.path(), &["add", "lib.rs"]);
    run_git(repo.path(), &["commit", "-m", "feat: add text"]);

    let out_branch_bad = run_bash_script(repo.path(), &script, &[]);
    assert!(
        !out_branch_bad.status.success(),
        "check-emdash-diff.sh must reject committed em dash via main...HEAD"
    );
}

#[test]
fn check_versions_validates_matching_and_mismatched_manifests_and_wix_package_scope() {
    let tmp = TempDir::new().expect("create temp dir");
    let script = script_path("check-versions.sh");

    fs::write(
        tmp.path().join("Cargo.toml"),
        "[workspace.package]\nversion = \"0.2.3\"\n",
    )
    .unwrap();
    fs::create_dir_all(tmp.path().join("driver-wdk")).unwrap();
    fs::write(
        tmp.path().join("driver-wdk/Cargo.toml"),
        "[workspace.package]\nversion = \"0.2.3\"\n",
    )
    .unwrap();
    fs::write(
        tmp.path().join("driver-wdk/zerovdd.inf"),
        "[Version]\nDriverVer = 11/24/2026,0.2.3.0\r\n",
    )
    .unwrap();
    fs::create_dir_all(tmp.path().join("installer")).unwrap();
    fs::write(
        tmp.path().join("installer/zerovdd.wxs"),
        concat!(
            "<Wix>\r\n",
            "  <Upgrade MinimumVersion=\"0.0.1\" />\r\n",
            "  <Package Name=\"zerovdd\" MinimumVersion=\"0.0.1\" Version=\"0.2.3.0\" />\r\n",
            "</Wix>\r\n",
        ),
    )
    .unwrap();

    let root_arg = tmp.path().to_string_lossy().replace('\\', "/");
    let out_ok = run_bash_script(
        tmp.path(),
        &script,
        &["--root", &root_arg, "--tag", "v0.2.3"],
    );
    assert!(
        out_ok.status.success(),
        "check-versions.sh should pass when Package Version matches despite MinimumVersion, stderr={}",
        String::from_utf8_lossy(&out_ok.stderr)
    );

    let out_bad_tag = run_bash_script(
        tmp.path(),
        &script,
        &["--root", &root_arg, "--tag", "v0.9.9"],
    );
    assert!(
        !out_bad_tag.status.success(),
        "check-versions.sh must fail on tag mismatch"
    );

    fs::write(
        tmp.path().join("driver-wdk/zerovdd.inf"),
        "[Version]\nDriverVer = 11/24/2026,0.2.9.0\r\n",
    )
    .unwrap();
    let out_bad_inf = run_bash_script(tmp.path(), &script, &["--root", &root_arg]);
    assert!(
        !out_bad_inf.status.success(),
        "check-versions.sh must fail on INF version mismatch"
    );

    fs::write(
        tmp.path().join("driver-wdk/zerovdd.inf"),
        "[Version]\nDriverVer = 11/24/2026,0.2.3.0\r\n",
    )
    .unwrap();
    fs::write(
        tmp.path().join("installer/zerovdd.wxs"),
        concat!(
            "<Wix>\r\n",
            "  <?define Version = \"0.2.3\" ?>\r\n",
            "  <Package Name=\"zerovdd\" MinimumVersion=\"0.0.1\" Version=\"$(var.Version)\" />\r\n",
            "</Wix>\r\n",
        ),
    )
    .unwrap();
    let out_var_ok = run_bash_script(tmp.path(), &script, &["--root", &root_arg]);
    assert!(
        out_var_ok.status.success(),
        "check-versions.sh must accept <?define Version = \"...\" ?> with $(var.Version), stderr={}",
        String::from_utf8_lossy(&out_var_ok.stderr)
    );

    fs::write(
        tmp.path().join("installer/zerovdd.wxs"),
        concat!(
            "<Wix>\r\n",
            "  <?define Version = \"0.2.9\" ?>\r\n",
            "  <Package Name=\"zerovdd\" MinimumVersion=\"0.0.1\" Version=\"$(var.Version)\" />\r\n",
            "</Wix>\r\n",
        ),
    )
    .unwrap();
    let out_var_bad = run_bash_script(tmp.path(), &script, &["--root", &root_arg]);
    assert!(
        !out_var_bad.status.success(),
        "check-versions.sh must fail when <?define Version = \"...\" ?> mismatches"
    );
}
